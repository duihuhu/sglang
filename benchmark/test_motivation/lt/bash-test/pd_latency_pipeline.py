# ---- nsys-rep (.nsys-rep → nvtx_PD_combined_stats.csv) ----
_D_POS_NAME_RE = re.compile(r"^(D_[A-Za-z0-9_]+)_pos(-?\d+)$")


def run_nsys_stats(nsys_bin: str, rep_path: str, output_prefix: str) -> str:
    cmd = [
        nsys_bin,
        "stats",
        "--report",
        "nvtx_gpu_proj_trace",
        "--timeunit=us",
        "--force-export=true",
        "--force-overwrite=true",
        "--format",
        "csv",
        "--output",
        output_prefix,
        rep_path,
    ]
    print("[run]", " ".join(cmd))
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr, file=sys.stderr)
        raise RuntimeError(f"nsys stats failed with exit code {proc.returncode}")

    # nsys report script typically generates: <prefix>_nvtx_gpu_proj_trace.csv
    candidates = sorted(glob.glob(output_prefix + "*.csv"), key=os.path.getmtime)
    if not candidates:
        raise FileNotFoundError(
            f"No CSV generated by nsys stats under prefix: {output_prefix}"
        )
    trace_csv = candidates[-1]
    print(f"[info] trace csv: {trace_csv}")
    return trace_csv


def detect_columns(header: List[str]) -> Tuple[str, str, Optional[str]]:
    lowered = [h.strip().lower() for h in header]

    name_col = None
    for i, h in enumerate(lowered):
        if h in ("name", "range", "range name", "nvtx range"):
            name_col = header[i]
            break
    if name_col is None:
        for i, h in enumerate(lowered):
            if "name" in h:
                name_col = header[i]
                break

    dur_col = None
    for i, h in enumerate(lowered):
        if "duration" in h or h.startswith("dur") or "time" in h and "range" in h:
            dur_col = header[i]
            break

    start_col: Optional[str] = None
    for i, h in enumerate(lowered):
        if h in ("start", "start_us", "start (us)", "start(us)", "begin", "begin (us)", "begin(us)"):
            start_col = header[i]
            break
    if start_col is None:
        for i, h in enumerate(lowered):
            if "start" in h or "begin" in h:
                start_col = header[i]
                break

    if name_col is None or dur_col is None:
        raise RuntimeError(
            "Cannot detect name/duration columns in CSV header. "
            f"header={header}"
        )
    return name_col, dur_col, start_col


def parse_trace_csv(csv_path: str) -> Dict[str, List[float]]:
    # Keep (start, duration) so we can sort by time even if nsys CSV is not ordered.
    values_with_start: Dict[str, List[Tuple[float, float]]] = defaultdict(list)
    with open(csv_path, "r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None:
            raise RuntimeError(f"CSV has no header: {csv_path}")
        name_col, dur_col, start_col = detect_columns(reader.fieldnames)
        print(f"[info] name_col={name_col}, dur_col={dur_col}, start_col={start_col}")

        row_idx = 0
        for row in reader:
            name = (row.get(name_col) or "").strip()
            if not name:
                continue
            raw_dur = (row.get(dur_col) or "").strip()
            if not raw_dur:
                continue
            try:
                dur = float(raw_dur)
            except ValueError:
                continue
            if start_col is None:
                start = float(row_idx)
            else:
                raw_start = (row.get(start_col) or "").strip()
                try:
                    start = float(raw_start)
                except ValueError:
                    start = float(row_idx)

            values_with_start[name].append((start, dur))
            row_idx += 1

    values: Dict[str, List[float]] = defaultdict(list)
    for name, arr in values_with_start.items():
        arr.sort(key=lambda x: x[0])
        values[name] = [dur for _, dur in arr]
    return values


def split_and_average_in_order(values: List[float], bucket_count: int) -> List[float]:
    """Split values into bucket_count contiguous buckets (in order), average each bucket.

    Always returns exactly bucket_count values.
    If bucket_count > len(values), empty buckets are filled by nearest sample value.
    """
    if not values:
        return []
    n = len(values)
    bucket_count = max(1, bucket_count)
    out = []
    for i in range(bucket_count):
        start = (i * n) // bucket_count
        end = ((i + 1) * n) // bucket_count
        if start < end:
            chunk = values[start:end]
            out.append(sum(chunk) / len(chunk))
        else:
            # For empty buckets (when bucket_count > n), use nearest sample.
            idx = min(start, n - 1)
            out.append(values[idx])
    return out


def strip_leading_colon(name: str) -> str:
    return name[1:] if name.startswith(":") else name


def write_combined_stats(
    values: Dict[str, List[float]],
    out_csv: str,
    d_bucket_count: int,
    d_num_cycles: int,
    d_pick_positions: List[int],
):
    rows = []
    pick_cols = [f"d_pos_{p}_us" for p in d_pick_positions]
    d_pos_group: Dict[str, Dict[int, List[float]]] = defaultdict(lambda: defaultdict(list))
    d_fallback_seq: Dict[str, List[float]] = defaultdict(list)

    for raw_name, arr in values.items():
        if not arr:
            continue
        name = strip_leading_colon(raw_name)

        if name.startswith("P_"):
            rows.append((name, len(arr), sum(arr) / len(arr), *([None] * len(d_pick_positions))))
            continue

        if not name.startswith("D_"):
            continue

        m = _D_POS_NAME_RE.match(name)
        if m is None:
            # Backward compatibility: old traces without decode-position suffix.
            d_fallback_seq[name].extend(arr)
            continue

        base_name = m.group(1)
        pos_val = int(m.group(2))
        d_pos_group[base_name][pos_val].extend(arr)

    # Prefer exact position-tagged stats when available.
    for base_name, pos_map in d_pos_group.items():
        d_values = [None] * len(d_pick_positions)
        sorted_positions = sorted(pos_map.keys())
        for i, pick_pos in enumerate(d_pick_positions):
            # pick_pos is 1-based output token position.
            idx = pick_pos - 1
            if 0 <= idx < len(sorted_positions):
                k = sorted_positions[idx]
                vals = pos_map[k]
                if vals:
                    d_values[i] = sum(vals) / len(vals)
        total_cnt = sum(len(v) for v in pos_map.values())
        rows.append((base_name, total_cnt, None, *d_values))

    # Fallback for non-position-tagged D_* markers.
    for name, arr in d_fallback_seq.items():
        if d_num_cycles <= 0:
            raise ValueError("--d-num-cycles must be >= 1")
        d_values = [None] * len(d_pick_positions)
        total_bucket_count = max(1, d_bucket_count) * d_num_cycles
        merged_total = split_and_average_in_order(arr, total_bucket_count)
        for i, pos in enumerate(d_pick_positions):
            idx_in_cycle = pos - 1
            vals: List[float] = []
            for c in range(d_num_cycles):
                idx = c * d_bucket_count + idx_in_cycle
                if 0 <= idx < len(merged_total):
                    vals.append(merged_total[idx])
            if vals:
                d_values[i] = sum(vals) / len(vals)
        rows.append((name, len(arr), None, *d_values))

    rows.sort(key=lambda x: x[0])
    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["op_name", "count", "mean_us", *pick_cols])
        for r in rows:
            w.writerow(r)
    print(f"[saved] {out_csv}")


def nvtx_rep_cli_main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Generate NVTX op stats from .nsys-rep: "
            "P_* ops -> mean, D_* ops -> p25/p50/p75/p90"
        )
    )
    parser.add_argument(
        "rep_file",
        type=str,
        help="Path to .nsys-rep file",
    )
    parser.add_argument(
        "--out-dir",
        type=str,
        default="/mnt/nvme1/lt/cache/nvtx_stats",
        help="Output directory for generated CSVs",
    )
    parser.add_argument(
        "--nsys-bin",
        type=str,
        default="nsys",
        help="Path to nsys executable",
    )
    parser.add_argument(
        "--d-bucket-count",
        type=int,
        default=128,
        help="For D_* ops, split sequential samples into this many ordered buckets and average each bucket.",
    )
    parser.add_argument(
        "--d-num-cycles",
        type=int,
        default=1,
        help=(
            "Number of concatenated decode rounds/cycles in this trace. "
            "Used to align D_* operator samples to the correct token position when num_seqs > batch_size."
        ),
    )
    parser.add_argument(
        "--d-pick-positions",
        type=str,
        default="32,64,128",
        help="1-based positions to pick from D bucket-averaged sequence (comma-separated), e.g. 32,64,128",
    )
    args = parser.parse_args()

    rep_file = os.path.abspath(args.rep_file)
    if not os.path.isfile(rep_file):
        raise FileNotFoundError(f"rep file not found: {rep_file}")

    os.makedirs(args.out_dir, exist_ok=True)
    trace_prefix = os.path.join(args.out_dir, "nvtx_gpu_proj_trace")

    trace_csv = run_nsys_stats(args.nsys_bin, rep_file, trace_prefix)
    values = parse_trace_csv(trace_csv)

    combined_csv = os.path.join(args.out_dir, "nvtx_PD_combined_stats.csv")
    d_pick_positions = [int(x.strip()) for x in args.d_pick_positions.split(",") if x.strip()]
    if any(p <= 0 for p in d_pick_positions):
        raise ValueError("--d-pick-positions must be positive 1-based integers.")

    # Ensure requested positions are representable in merged buckets.
    # Example: pick 255 requires at least 255 buckets.
    effective_bucket_count = max(args.d_bucket_count, max(d_pick_positions))
    if effective_bucket_count != args.d_bucket_count:
        print(
            f"[info] auto bump d_bucket_count: {args.d_bucket_count} -> "
            f"{effective_bucket_count} to satisfy d_pick_positions={d_pick_positions}"
        )

    if args.d_num_cycles <= 0:
        raise ValueError("--d-num-cycles must be >= 1")

    write_combined_stats(
        values,
        combined_csv,
        d_bucket_count=effective_bucket_count,
        d_num_cycles=args.d_num_cycles,
        d_pick_positions=d_pick_positions,
    )

    p_ops = sum(1 for k in values if strip_leading_colon(k).startswith("P_"))
    d_ops = sum(1 for k in values if strip_leading_colon(k).startswith("D_"))
    print(f"[done] P_ops={p_ops}, D_ops={d_ops}")



# ---- merge-sync (JSON dumps → long table) ----
_ALLOWED_OPS = {"A", "F", "TTFT", "TPOT"}


def _parse_run_dir_name(run_dir_name: str) -> Tuple[int, int, int, int, int]:
    # base like "tp1_in128_clk210_bs4_ol128"
    parts = run_dir_name.split("_")
    if len(parts) < 3:
        raise RuntimeError(f"Cannot parse run metadata from dir: {run_dir_name}")
    tp = int(parts[0].replace("tp", ""))
    input_len = int(parts[1].replace("in", ""))
    gpu_clock = int(parts[2].replace("clk", ""))
    batch_size = 1
    target_output_len = 1
    for part in parts[3:]:
        if part.startswith("bs"):
            batch_size = int(part.replace("bs", ""))
        elif part.startswith("ol"):
            target_output_len = int(part.replace("ol", ""))
    return tp, input_len, gpu_clock, batch_size, target_output_len


def _load_and_merge_dump_values(
    processed_dir: str,
) -> Tuple[Dict[str, List[float]], Dict[str, List[float]]]:
    # Expect multiple per-rank json dumps written by llama.py signal/atexit handler.
    dump_paths = sorted(glob.glob(os.path.join(processed_dir, "*.json")))
    if not dump_paths:
        raise FileNotFoundError(f"No *.json dumps found under: {processed_dir}")

    merged: Dict[str, List[float]] = defaultdict(list)
    merged_energy_uj: Dict[str, List[float]] = defaultdict(list)
    for p in dump_paths:
        try:
            with open(p, "r", encoding="utf-8") as f:
                payload = json.load(f)
        except json.JSONDecodeError as e:
            # Likely a partially-written dump (process terminated while writing).
            print(f"[warn] skip broken json dump: {p}. err={e}")
            continue
        values = payload.get("values") or {}
        energy_uj = payload.get("energy_uj") or {}
        for op_key, dur_list in values.items():
            if not isinstance(dur_list, list):
                continue
            merged[op_key].extend([float(x) for x in dur_list])
        for op_key, e_list in energy_uj.items():
            if not isinstance(e_list, list):
                continue
            merged_energy_uj[op_key].extend([float(x) for x in e_list])
    return merged, merged_energy_uj


def _aggregate_sync_op_dump_run(
    *,
    processed_dir: str,
    output_lens: List[int],
    bench_stage: str,
) -> List[Dict[str, object]]:
    run_dir = os.path.dirname(processed_dir)
    tp, input_len, gpu_clock, batch_size, target_output_len = _parse_run_dir_name(
        os.path.basename(run_dir)
    )

    values, energy_uj_map = _load_and_merge_dump_values(processed_dir)

    rows_out: List[Dict[str, object]] = []

    # In D proxy mode, recover original input length from:
    # proxy_input_len = original_input_len + target_output_len - 1
    input_len_display = input_len
    if bench_stage == "D":
        input_len_display = input_len - target_output_len + 1

    # P stage: for each P_* op, use mean across all samples and replicate across output_len.
    if bench_stage == "P":
        for op_key, arr in values.items():
            if not op_key.startswith("P_"):
                continue
            if not arr:
                continue
            op_name = op_key[len("P_") :]
            if op_name not in _ALLOWED_OPS:
                continue
            mean_us = sum(arr) / len(arr)
            cnt = len(arr)
            energy_mean = None
            e_vals = energy_uj_map.get(op_key) or []
            if e_vals:
                energy_mean = sum(e_vals) / len(e_vals)
            for out_len in output_lens:
                out_len_val = target_output_len if target_output_len > 1 else out_len
                rows_out.append(
                    {
                        "tp": tp,
                        "input_len": input_len_display,
                        "output_len": out_len_val,
                        "gpu_clock": gpu_clock,
                        "batch_size": batch_size,
                        "stage": "P",
                        "op_name": op_name,
                        "count": cnt,
                        "latency_us": mean_us,
                        "energy_uj": energy_mean,
                    }
                )

    # D stage: group by base name (D_*) and decode position suffix (_pos{...}).
    d_group: Dict[str, Dict[int, List[float]]] = defaultdict(lambda: defaultdict(list))
    # Fallback: for D_* ops without _pos suffix (e.g. stage-level TPOT),
    # replicate the mean across all output_lens.
    d_fallback: Dict[str, List[float]] = defaultdict(list)  # op_key -> durations
    for op_key, arr in values.items():
        if not op_key.startswith("D_"):
            continue
        m = _D_POS_NAME_RE.match(op_key)
        if m is None:
            d_fallback[op_key].extend(arr)
            continue
        base_name = m.group(1)  # includes D_ prefix
        pos_val = int(m.group(2))
        d_group[base_name][pos_val].extend(arr)

    if bench_stage == "D":
        for base_name, pos_map in d_group.items():
            if not pos_map:
                continue
            op_name = base_name[len("D_") :]
            if op_name not in _ALLOWED_OPS:
                continue
            sorted_positions = sorted(pos_map.keys())
            total_cnt = sum(len(v) for v in pos_map.values())
            for out_len in output_lens:
                idx = out_len - 1  # old convention: pick_pos is 1-based
                if idx < 0 or idx >= len(sorted_positions):
                    continue
                pos_val = sorted_positions[idx]
                vals = pos_map.get(pos_val) or []
                if not vals:
                    continue
                mean_us = sum(vals) / len(vals)
                e_vals = energy_uj_map.get(f"{base_name}_pos{pos_val}") or []
                energy_mean = (sum(e_vals) / len(e_vals)) if e_vals else None
                out_len_val = target_output_len if target_output_len > 1 else out_len
                rows_out.append(
                    {
                        "tp": tp,
                        "input_len": input_len_display,
                        "output_len": out_len_val,
                        "gpu_clock": gpu_clock,
                        "batch_size": batch_size,
                        "stage": "D",
                        "op_name": op_name,
                        "count": total_cnt,
                        "latency_us": mean_us,
                        "energy_uj": energy_mean,
                    }
                )

    # Fallback D_* ops without explicit decode position suffix.
    if bench_stage == "D":
        for op_key, arr in d_fallback.items():
            if not arr:
                continue
            # op_key like "D_TPOT" => op_name "TPOT"
            op_name = op_key[len("D_") :]
            if op_name not in _ALLOWED_OPS:
                continue
            mean_us = sum(arr) / len(arr)
            cnt = len(arr)
            e_vals = energy_uj_map.get(op_key) or []
            energy_mean = (sum(e_vals) / len(e_vals)) if e_vals else None
            for out_len in output_lens:
                out_len_val = target_output_len if target_output_len > 1 else out_len
                rows_out.append(
                    {
                        "tp": tp,
                        "input_len": input_len_display,
                        "output_len": out_len_val,
                        "gpu_clock": gpu_clock,
                        "batch_size": batch_size,
                        "stage": "D",
                        "op_name": op_name,
                        "count": cnt,
                        "latency_us": mean_us,
                        "energy_uj": energy_mean,
                    }
                )

    return rows_out


def merge_sync_cli_main() -> None:
    parser = argparse.ArgumentParser(
        description="Convert sync-op-bench llama.py dumps into pd_latency_big_table.csv for pivot script."
    )
    parser.add_argument(
        "--work-dir",
        type=str,
        default="bash-test/pd_batch_work",
        help="Directory containing tp*_in*_clk*_bs*/processed/*_rank*.json dumps.",
    )
    parser.add_argument(
        "--output-lens",
        type=str,
        default="64,256,512",
        help="Comma-separated output/token positions to pick for D stage.",
    )
    parser.add_argument(
        "--bench-stage",
        type=str,
        default="D",
        choices=["P", "D", "p", "d"],
        help="Export only this stage from dumps.",
    )
    parser.add_argument(
        "--final-csv",
        type=str,
        default="bash-test/pd_latency_big_table.csv",
        help="Output long-format CSV path (same schema expected by pivot subcommand).",
    )
    args = parser.parse_args()

    work_dir = os.path.abspath(args.work_dir)
    output_lens = [int(x.strip()) for x in args.output_lens.split(",") if x.strip()]
    bench_stage = str(args.bench_stage).strip().upper()
    if not output_lens:
        raise ValueError("--output-lens must not be empty")

    processed_dirs = sorted(glob.glob(os.path.join(work_dir, "tp*", "processed")))
    if not processed_dirs:
        raise RuntimeError(f"No processed dirs found under: {work_dir}")

    out_rows: List[Dict[str, object]] = []
    missing_dump_dirs: List[str] = []
    for processed_dir in processed_dirs:
        if not glob.glob(os.path.join(processed_dir, "*.json")):
            missing_dump_dirs.append(processed_dir)
            continue
        out_rows.extend(
            _aggregate_sync_op_dump_run(
                processed_dir=processed_dir,
                output_lens=output_lens,
                bench_stage=bench_stage,
            )
        )

    if missing_dump_dirs:
        preview = ", ".join(missing_dump_dirs[:3])
        suffix = "" if len(missing_dump_dirs) <= 3 else f", ... (+{len(missing_dump_dirs) - 3} more)"
        print(
            "[warn] skip processed dirs without sync-op dumps: "
            f"{len(missing_dump_dirs)} dirs. examples: {preview}{suffix}"
        )

    if not out_rows:
        raise RuntimeError(
            "No rows exported from sync-op dumps. "
            "No valid *.json dump files were found under any tp*/processed directory. "
            "Current work-dir may contain only bench CSV artifacts (e.g. *_af_ttft_af.csv), "
            "which are not sync-op dump inputs."
        )

    out_csv_path = os.path.abspath(args.final_csv)
    os.makedirs(os.path.dirname(out_csv_path), exist_ok=True)
    with open(out_csv_path, "w", newline="", encoding="utf-8") as f:
        fieldnames = [
            "tp",
            "input_len",
            "output_len",
            "gpu_clock",
            "batch_size",
            "stage",
            "op_name",
            "count",
            "latency_us",
            "energy_uj",
        ]
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in out_rows:
            w.writerow(r)

    print(f"[saved] {out_csv_path}")
    print(f"[info] rows: {len(out_rows)}")



